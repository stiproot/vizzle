"""`vizzle hybrid` end to end: build, --check, and the exit-code split.

Exit 1 is the author's to fix (drift, layout lint, a stale SVG); exit 2 is
the command unable to run (docs/plans/impl/hybrid.md §3).
"""

import json
from pathlib import Path

import pytest
from click.testing import CliRunner
from vizzle_cli import render as render_mod
from vizzle_cli.cli import main

LEGEND = {"x": 600, "y": 140, "w": 340, "rows": [["swatch", "primary", "process"]], "note": None}


def runtime_spec(**over: object) -> dict:
    spec = {
        "title": "Svc at runtime",
        "subtitle": "One process and the core it links.",
        "footnote": "The links band is computed from the imports.",
        "family": "primary",
        "canvas": {"width": 1000},
        "vizzle": ["ws"],
        "shared": ["ws:packages/core"],
        "nodes": [
            {
                "id": "svc",
                "type": "component",
                "name": "svc process",
                "stack": "TypeScript",
                "x": [40, 520],
                "y": 140,
                "modules": [{"name": "svc", "refs": ["ws:apps/svc"]}],
                "links": "auto",
            }
        ],
        "edges": [],
        "legend": LEGEND,
    }
    spec.update(over)
    return spec


def concept_spec() -> dict:
    return {
        "title": "A concept",
        "subtitle": "Two boxes that cite their source.",
        "footnote": "Cited paths hold it to the tree.",
        "canvas": {"width": 1000},
        "vizzle": [],
        "nodes": [
            {"id": "a", "type": "box", "name": "Core", "x": [40, 280], "y": 140, "path": "packages/core/src/index.ts"},
            {"id": "b", "type": "box", "name": "Svc", "x": [40, 280], "y": 320, "path": ["apps/svc/src/main.ts"]},
        ],
        "edges": [{"from": "b", "to": "a", "label": "imports"}],
        "legend": {"x": 600, "y": 140, "w": 340, "rows": [["edge", None, "an import"]], "note": None},
    }


@pytest.fixture()
def ws(tmp_path: Path) -> Path:
    """A two-package workspace, `apps/svc` importing `@x/core`, with one runtime and one concept spec."""
    files = {
        "packages/core/package.json": '{"name": "@x/core"}',
        "packages/core/src/index.ts": "export class Core {}\n",
        "apps/svc/package.json": '{"name": "svc"}',
        "apps/svc/src/main.ts": 'import { Core } from "@x/core";\nclass Svc {}\n',
    }
    for rel, text in files.items():
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text(text)
    specs = tmp_path / "docs/diagrams/hybrid"
    specs.mkdir(parents=True)
    write(specs / "vizzle-passes.json", {"passes": {"ws": {"args": ["-I", "packages/**", "-I", "apps/**"]}}})
    write(specs / "runtime.json", runtime_spec())
    write(specs / "concept.json", concept_spec())
    return tmp_path


def write(path: Path, value: dict) -> None:
    path.write_text(json.dumps(value, indent=2))


def hybrid(ws: Path, *args: str):
    return CliRunner().invoke(main, ["hybrid", "--root", str(ws), *args])


def test_builds_every_spec_next_to_its_directory_and_checks_clean(ws: Path) -> None:
    result = hybrid(ws)
    assert result.exit_code == 0, result.output
    svg = (ws / "docs/diagrams/runtime.svg").read_text()
    assert svg.startswith("<svg ")
    lines = svg.splitlines()
    assert lines[1].startswith("<!-- GENERATED by vizzle hybrid ")
    assert "from docs/diagrams/hybrid/runtime.json (passes: ws)" in lines[1]
    # the links band is the import closure into the shared core, from the real pass
    assert 'links</tspan><tspan class="small"> — core</tspan>' in svg
    assert (ws / "docs/diagrams/concept.svg").exists()
    check = hybrid(ws, "--check")
    assert check.exit_code == 0, check.output
    assert "✓ runtime" in check.output


def test_check_fails_on_a_hand_edited_svg_and_writes_nothing(ws: Path) -> None:
    assert hybrid(ws).exit_code == 0
    svg = ws / "docs/diagrams/concept.svg"
    svg.write_text(svg.read_text().replace("Core", "Kore"))
    edited = svg.read_text()
    result = hybrid(ws, "--check")
    assert result.exit_code == 1, result.output
    assert "concept: docs/diagrams/concept.svg differs from a fresh build" in result.output
    assert svg.read_text() == edited


def test_a_renamed_module_is_drift_naming_the_component_and_the_ref(ws: Path) -> None:
    # a module's id is <group>/<leaf of its name>, and a manifest names it
    (ws / "apps/svc/package.json").write_text('{"name": "server"}')
    result = hybrid(ws, "runtime")
    assert result.exit_code == 1, result.output
    assert '[runtime] drift: svc › "svc" names ws:apps/svc, which vizzle no longer reports' in result.output
    assert "Stopped: this diagram and the ones after it were not written." in result.output
    assert not (ws / "docs/diagrams/runtime.svg").exists()


def test_a_new_package_in_scope_is_drift_until_placed_or_omitted(ws: Path) -> None:
    (ws / "packages/extra/src").mkdir(parents=True)
    (ws / "packages/extra/package.json").write_text('{"name": "extra"}')
    (ws / "packages/extra/src/index.ts").write_text("export class Extra {}\n")
    result = hybrid(ws, "runtime")
    assert result.exit_code == 1, result.output
    assert "vizzle reports ws:packages/extra in scope, but the spec places it nowhere" in result.output
    write(ws / "docs/diagrams/hybrid/runtime.json", runtime_spec(omit={"ws:packages/extra": "not part of svc"}))
    assert hybrid(ws, "runtime").exit_code == 0


def test_a_deleted_cited_path_is_drift_naming_the_node(ws: Path) -> None:
    (ws / "apps/svc/src/main.ts").unlink()
    result = hybrid(ws, "concept")
    assert result.exit_code == 1, result.output
    assert "[concept] drift: b cites apps/svc/src/main.ts, which is gone from the tree" in result.output


def test_overlapping_boxes_fail_the_lint_naming_the_rule_and_both_ids(ws: Path) -> None:
    spec = concept_spec()
    spec["nodes"][1]["y"] = 160
    spec["edges"] = []
    write(ws / "docs/diagrams/hybrid/concept.json", spec)
    result = hybrid(ws, "concept")
    assert result.exit_code == 1, result.output
    assert "[concept] layout: overlap: node a × node b" in result.output


def test_text_wider_than_its_box_fails_the_lint(ws: Path) -> None:
    spec = concept_spec()
    spec["nodes"][0]["name"] = "A title far too wide for a box this narrow"
    write(ws / "docs/diagrams/hybrid/concept.json", spec)
    result = hybrid(ws, "concept")
    assert result.exit_code == 1, result.output
    assert 'layout: a: "A title far too wide for a box this narrow" is wider than its box' in result.output


def test_a_misspelt_field_cannot_run(ws: Path) -> None:
    spec = concept_spec()
    spec["nodez"] = spec.pop("nodes")
    write(ws / "docs/diagrams/hybrid/concept.json", spec)
    result = hybrid(ws, "--check")
    assert result.exit_code == 2, result.output
    assert "unknown field `nodez`" in result.output


@pytest.mark.parametrize(
    ("table", "message"),
    [
        ({"passes": {}}, '[runtime] spec names vizzle pass "ws", which the pass table does not define'),
        ({"passes": {"ws": {"args": ["--weights"]}}}, 'pass "ws": weights shapes how a graph is drawn'),
        ({"passes": {"ws": {"args": ["--no-such-flag"]}}}, 'pass "ws": No such option'),
        ({"passes": {"ws": {"argz": []}}}, 'pass "ws" must be {"args": [strings]}'),
        ({"passez": {}}, "vizzle-passes.json: not a pass table: unknown field `passez`"),
        (["ws"], "vizzle-passes.json: not a pass table: expected an object"),
    ],
)
def test_a_bad_pass_table_cannot_run(ws: Path, table: dict, message: str) -> None:
    write(ws / "docs/diagrams/hybrid/vizzle-passes.json", table)
    result = hybrid(ws, "runtime")
    assert result.exit_code == 2, result.output
    assert message in result.output


def test_a_pass_defined_twice_cannot_run(ws: Path) -> None:
    path = ws / "docs/diagrams/hybrid/vizzle-passes.json"
    path.write_text('{"passes": {"ws": {"args": []}, "ws": {"args": ["-I", "apps/**"]}}}', encoding="utf-8")
    result = hybrid(ws, "runtime")
    assert result.exit_code == 2, result.output
    assert 'pass "ws" is defined twice' in result.output


def test_the_old_version_pin_is_ignored_with_a_note(ws: Path) -> None:
    write(
        ws / "docs/diagrams/hybrid/vizzle-passes.json",
        {"vizzle": "0.13.0", "passes": {"ws": {"args": ["-I", "packages/**", "-I", "apps/**"]}}},
    )
    result = hybrid(ws, "runtime")
    assert result.exit_code == 0, result.output
    assert "pins vizzle 0.13.0; the pin is ignored" in result.output


def test_an_unknown_name_and_a_missing_directory_cannot_run(ws: Path, tmp_path: Path) -> None:
    assert hybrid(ws, "nope").exit_code == 2
    assert hybrid(ws, "--dir", str(tmp_path / "none")).exit_code == 2


def test_png_without_a_browser_cannot_run_and_svgs_need_none(ws: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(render_mod, "find_chrome", lambda: None)
    result = hybrid(ws, "--png")
    assert result.exit_code == 2, result.output
    assert "--png needs Chrome" in result.output
    assert hybrid(ws).exit_code == 0


def test_a_relative_dir_is_a_shell_path_and_outputs_go_to_its_parent(ws: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.chdir(ws)
    elsewhere = ws / "pictures/hybrid"
    elsewhere.mkdir(parents=True)
    write(elsewhere / "concept.json", concept_spec())
    result = CliRunner().invoke(main, ["hybrid", "--dir", "pictures/hybrid"])
    assert result.exit_code == 0, result.output
    assert "from pictures/hybrid/concept.json (passes: none)" in (ws / "pictures/concept.svg").read_text()
